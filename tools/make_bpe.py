# 加一些英文与符号，让演示能处理混合输入
EXTRA = "大模型 LLM Transformer token 注意力 softmax 梯度 numpy python 推理 训练 采样".split()

text = "".join(SENTENCES) + "".join(EXTRA)
chars = list(text)
merges = []
NUM = 260
for step in range(NUM):
    pairs = collections.Counter()
    for a, b in zip(chars, chars[1:]):
        if len(a) + len(b) > 4:
            continue
        pairs[(a, b)] += 1
    if not pairs:
        break
    (a, b), cnt = pairs.most_common(1)[0]
    if cnt < 2:
        break
    merges.append([a, b])
    out, i = [], 0
    while i < len(chars):
        if i < len(chars) - 1 and chars[i] == a and chars[i + 1] == b:
            out.append(a + b); i += 2
        else:
            out.append(chars[i]); i += 1
    chars = out
    if step % 50 == 0:
        print(f"merge {step:3d}  {a}+{b}  count={cnt}  tokens={len(chars)}")

print("merges", len(merges), "final tokens", len(chars), "of", len(list(text)))
os.makedirs("build", exist_ok=True)
json.dump({"merges": merges, "alphabet": sorted(set(text))}, open("build/bpe.json", "w"), ensure_ascii=False)
print("wrote build/bpe.json", os.path.getsize("build/bpe.json"), "bytes")
